export function getLanguageFromCountry(country) {
  const c = String(country || '').trim().toLowerCase();
  if (['russia', 'russian federation', 'россия', 'belarus', 'kazakhstan'].includes(c)) return 'ru';
  if (['france', 'belgium', 'luxembourg', 'monaco', 'senegal', 'haiti'].includes(c)) return 'fr';
  if (
    ['spain', 'mexico', 'argentina', 'colombia', 'peru', 'chile', 'ecuador', 'cuba', 'venezuela', 'guatemala', 'costa rica', 'bolivia', 'uruguay', 'paraguay', 'honduras', 'el salvador', 'nicaragua', 'panama', 'dominican republic', 'puerto rico'].includes(c)
  ) {
    return 'es';
  }
  if (['china', 'taiwan', 'singapore', 'hong kong', '中国'].includes(c)) return 'zh';
  return 'en';
}

